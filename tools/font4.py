_DIGITS = [
    "### #.# #.# #.# #.# #.# ###", ".#. ##. .#. .#. .#. .#. ###",
    "##. ..# ..# .#. #.. #.. ###", "##. ..# ..# .#. ..# ..# ##.",
    "#.# #.# #.# ### ..# ..# ..#", "### #.. #.. ##. ..# ..# ##.",
    ".## #.. #.. ##. #.# #.# .#.", "### ..# ..# .#. .#. .#. .#.",
    ".#. #.# #.# .#. #.# #.# .#.", ".#. #.# #.# .## ..# ..# ##.",
]
_PUNCT = {
    0x3E: "#.# #.#", 0x3F: "#.# #.#", 0x40: ".#. .#. #..",
    0x41: "... #.# .#. ### .#. #.#", 0x42: "... #.. ##. ### ##. #..",
    0x43: "... ... ... ### .#.", 0x44: "... ... .#. ... ... .#.",
    0x45: "... ... ... ... ... #.# #.#", 0x47: "... ... ... ... ... .#. .#.",
    0x48: "... ... ... ... .#. .#. #..", 0x49: "... ... ... ### ",
    0x4B: ".#. #.# ..# .#. .#. ... .#.", 0x4C: ".#. .#. .#. .#. .#. ... .#.",
    0x4D: "... .#. ... ... .#. #..", 0x4E: "#.. .#. .#. .#. .#. .#. #..",
    0x4F: "..# .#. .#. .#. .#. .#. ..#", 0x50: "..# .#. .##", 0x51: "..# .#. .##",
    0x52: "..# ..# .#. ... ... #.. #..", 0x53: "##. ##. .#. #..", 0x54: ".## .## ..# .#.",
}

GLYPHS = {}
for i, rows in enumerate(_DIGITS):
    GLYPHS[i] = _rows(rows)
for i, ch in enumerate("abcdefghijklmnopqrstuvwxyz"):
    GLYPHS[0x0A + i] = _rows(_LOWER[ch])
for i, ch in enumerate("ABCDEFGHIJKLMNOPQRSTUVWXYZ"):
    GLYPHS[0x24 + i] = _rows(_UPPER[ch])
for tile, rows in _PUNCT.items():
    GLYPHS[tile] = _rows(rows)


def glyph(tile, color=1):
    """8 rows of 4 pixel values (0 or COLOR), or None if not a font tile."""
    rows = GLYPHS.get(tile)
    if rows is None:
        return None
    return [[color if c == "#" else 0 for c in row] + [0] for row in rows]
